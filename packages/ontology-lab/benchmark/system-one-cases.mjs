export function validateCases(cases = SYSTEM_ONE_CASES) {
  if (!Array.isArray(cases) || cases.length === 0) throw new Error("cases must be a non-empty array");
  const ids = new Set();
  for (const item of cases) {
    if (!item || typeof item !== "object") throw new Error("each case must be an object");
    if (typeof item.id !== "string" || !item.id) throw new Error("each case needs an id");
    if (ids.has(item.id)) throw new Error(`duplicate case id: ${item.id}`);
    ids.add(item.id);
    if (!['crisp', 'subjective'].includes(item.kind)) throw new Error(`invalid kind: ${item.id}`);
    if (typeof item.label !== "boolean") throw new Error(`invalid label: ${item.id}`);
    if (!item.state || item.question?.type !== "noul") throw new Error(`invalid state or question: ${item.id}`);
  }
  return cases;
}

